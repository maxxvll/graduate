-- ================================================
-- chat_session 表索引
-- ================================================

-- 复合索引：用户ID + 删除 + 更新 + ID（降序）
-- 用途：会话增量同步（支持游标分页）
CREATE INDEX idx_chat_session_user_sync
ON chat_session(user_id, is_deleted, updated_at DESC, id DESC)
COMMENT '会话增量同步优化索引';

-- ================================================
-- chat_group_member 表索引
-- ================================================

-- 复合索引：用户ID + 退出标记 + 群组ID
-- 用途：用户群组关系变更同步
CREATE INDEX idx_chat_group_member_sync
ON chat_group_member(user_id, is_quit, group_id)
COMMENT '群组成员同步优化索引';
